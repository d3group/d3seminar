import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {createInterface} from 'node:readline';
import {fileURLToPath} from 'node:url';

const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const fixture = spawn('python3', ['tests/browser_fixture.py', '--organizer', '--admin'], {cwd:root, stdio:['ignore', 'pipe', 'inherit']});
let browser;
try {
  const details = await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Admin fixture did not start')), 15000);
    createInterface({input:fixture.stdout}).once('line', line => { clearTimeout(timeout); resolve(JSON.parse(line)); });
    fixture.once('exit', code => { clearTimeout(timeout); reject(new Error(`Fixture exited: ${code}`)); });
  });
  browser = await chromium.launch({headless:true});
  await mkdir(new URL('../test-results/', import.meta.url), {recursive:true});
  const page = await browser.newPage({viewport:{width:1440, height:1000}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  const url = details.base + 'admin.html#token=' + 'T'.repeat(43);
  await page.goto(url);
  await page.getByRole('button', {name:'Users', exact:true}).click();
  await page.locator('#users-count').filter({hasText:'1 users'}).waitFor();
  await page.getByRole('button', {name:'Edit Browser Test', exact:true}).click();
  await page.getByLabel('Organizer access', {exact:true}).uncheck();
  await page.getByRole('button', {name:'Save user', exact:true}).click();
  await page.locator('#users-notice.error').filter({hasText:'Keep at least one'}).waitFor();
  await page.getByRole('button', {name:'Cancel', exact:true}).click();
  await page.getByRole('button', {name:'Add user', exact:true}).click();
  await page.getByLabel('Full name', {exact:true}).fill('Bea Example');
  await page.getByRole('textbox', {name:'Email', exact:true}).fill('bea@example.org');
  await page.getByLabel('Academic role').selectOption('Professor');
  await page.getByRole('button', {name:'Save user', exact:true}).click();
  await page.locator('#users-notice').filter({hasText:'User saved.'}).waitFor();
  await page.getByRole('row').filter({hasText:'Bea Example'}).getByText('Draft', {exact:true}).waitFor();
  await page.getByRole('button', {name:'Edit Bea Example', exact:true}).click();
  await page.getByLabel('Seminar 1', {exact:true}).check();
  await page.getByLabel('Organizer access', {exact:true}).check();
  await page.getByRole('button', {name:'Save user', exact:true}).click();
  await page.locator('#users-count').filter({hasText:'2 organizers'}).waitFor();
  await page.screenshot({path:root+'test-results/admin-users-desktop.png', fullPage:true});
  await page.getByRole('button', {name:'Edit Bea Example', exact:true}).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', {name:'Remove user', exact:true}).click();
  await page.locator('#users-notice').filter({hasText:'User removed.'}).waitFor();
  assert.equal(await page.getByRole('button', {name:'Edit Bea Example', exact:true}).count(), 0);
  await page.getByLabel('Show removed users').check();
  await page.getByRole('button', {name:'Restore Bea Example', exact:true}).click();
  await page.getByRole('button', {name:'Save user', exact:true}).click();
  await page.locator('#users-notice').filter({hasText:'User saved.'}).waitFor();
  await page.getByRole('row').filter({hasText:'Bea Example'}).getByText('Draft', {exact:true}).waitFor();
  await page.setViewportSize({width:390, height:844});
  await page.getByRole('button', {name:'Edit Bea Example', exact:true}).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:root+'test-results/admin-users-mobile.png', fullPage:true});
  await page.getByRole('button', {name:'Email', exact:true}).click();
  await page.getByRole('button', {name:'Preview recipients and emails', exact:true}).click();
  await page.locator('#mail-review').waitFor();
  assert.equal((await page.locator('#mail-messages').textContent()).includes('T'.repeat(43)), false);
  await page.getByRole('button', {name:'Queue these emails', exact:true}).click();
  await page.locator('#mail-notice').filter({hasText:'Emails queued.'}).waitFor();
  await page.locator('#mail-batches summary').click();
  await page.getByRole('button', {name:'Cancel unsent emails', exact:true}).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:root+'test-results/admin-email-mobile.png', fullPage:true});
  await page.getByRole('button', {name:'Cancel unsent emails', exact:true}).click();
  await page.locator('#mail-notice').filter({hasText:'Unsent emails cancelled.'}).waitFor();
  const visitor = await browser.newPage();
  await visitor.goto(details.base + 'admin.html');
  await visitor.locator('#admin-notice.error').waitFor();
  assert.equal(await visitor.locator('#admin-panels').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log('Admin panel: user edits, multiple organizers, last-organizer protection, removal/restoration, private previews, queue/cancellation and mobile layouts passed.');
} finally {
  if (browser) await browser.close();
  fixture.kill('SIGTERM');
}
